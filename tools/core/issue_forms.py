"""The lists of mods in the GitHub issue forms, generated from the meta.xml of each mod.

GitHub reads an issue form as a static file, so a form cannot load its options from another file.
Thus each list of mods in a form is generated. Two YAML comments bound the list, and the generator
owns only the lines between them. The maintainer puts the comments in the form. GitHub ignores YAML
comments. `zwm lint issue-forms` writes the lists, and `zwm lint issue-forms-check` fails when a
list is out of date.
"""

import glob
import io
import json
import os
import re

from .mod_cli import discover_mods
from .mod_meta import display_name, meta_path_for
from .paths import REPO_ROOT

FORMS_DIR = os.path.join(REPO_ROOT, ".github", "ISSUE_TEMPLATE")
_START = "# mod-list: generated by `zwm lint issue-forms`, do not edit"
_END = "# /mod-list"
# The start comment, the lines of the list, and the end comment, with the same indent.
_SECTION = re.compile(
    r"^(?P<indent>[ \t]*)" + re.escape(_START) + r"\n(?:.*\n)*?(?P=indent)" + re.escape(_END) + r"$",
    re.MULTILINE,
)
# A name with only these characters is a plain YAML string. Any other name is quoted.
_PLAIN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 .\-]*$")


def mod_names():
    """The name of each mod with a meta.xml, as a list of the mods shows it, in order of the name."""
    return sorted(display_name(mod) for mod in discover_mods() if os.path.isfile(meta_path_for(mod)))


def _item(name):
    return name if _PLAIN.match(name) else json.dumps(name)


def _render(text, names):
    def section(match):
        indent = match.group("indent")
        lines = [indent + _START] + [indent + "- " + _item(name) for name in names] + [indent + _END]
        return "\n".join(lines)

    return _SECTION.sub(section, text)


def _forms():
    """The forms that hold a list of mods. A file without the comments, such as config.yml, is skipped."""
    paths = sorted(glob.glob(os.path.join(FORMS_DIR, "*.yml")) + glob.glob(os.path.join(FORMS_DIR, "*.yaml")))
    for path in paths:
        with io.open(path, encoding="utf-8") as handle:
            text = handle.read()
        if _SECTION.search(text):
            yield path, text


def _relative(path):
    return os.path.relpath(path, REPO_ROOT).replace(os.sep, "/")


def check_issue_forms():
    """Return a problem string for each form whose list of mods is out of date."""
    names = mod_names()
    return [
        "{0}: the list of mods is out of date; run `zwm lint issue-forms`".format(_relative(path))
        for path, text in _forms()
        if _render(text, names) != text
    ]


def write_issue_forms():
    """Rewrite the list of mods in each form. Returns the forms that changed."""
    names = mod_names()
    updated = []
    for path, text in _forms():
        rendered = _render(text, names)
        if rendered != text:
            with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(rendered)
            updated.append(_relative(path))
    return updated
